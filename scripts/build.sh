#!/usr/bin/env bash
# Produce a self-contained deployment script; no runtime module downloads.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
output=${1:-dist/sb.sh}
mkdir -p "$(dirname "$output")"
tmp=$(mktemp "${output}.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
  printf '#!/usr/bin/env bash\n# Generated by scripts/build.sh; edit sb.sh and lib/*.sh instead.\n'
  sed -n '/^SB_VERSION=/p' sb.sh
  printf 'SB_ENTRY=${BASH_SOURCE[0]}\n'
  while IFS= read -r module; do
    printf '\n# === %s ===\n' "$module"
    cat "lib/$module.sh"
  done < lib/modules.list
  cat <<'ENTRY'

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
  main "$@"
  exit $?
fi
ENTRY
} > "$tmp"
bash -n "$tmp"
chmod 755 "$tmp"
mv -f "$tmp" "$output"
