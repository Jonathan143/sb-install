cert_menu() {
  local d dom c rc=0
  ui_title "证书管理"
  echo "已保存的证书:"
  for d in "$CERT_DIR"/*/ "$CERT_DIR"/*/self.*/; do
    [[ -s ${d}fullchain.pem ]] || continue
    dom=${d#"$CERT_DIR/"}; dom=${dom%/}
    printf '  %-32s 到期: %s%s\n' "$dom" "$(cert_expiry "${d}fullchain.pem")" "$([[ -e ${d}.selfsigned ]] && echo '  (自签)')"
  done
  echo
  echo "  1) 强制续期某个域名（acme.sh）   0) 返回"
  c=$(ask_choice "请选择" 1 0) || return 0
  [[ $c != 0 ]] || { UI_SKIP_PAUSE=1; return 0; }
  if [[ $c == 1 ]]; then
    if [[ -x $ACME_SH ]]; then
      dom=$(ask_domain "域名") || return 1
      "$ACME_SH" --renew -d "$dom" --ecc --force && info "续期完成（证书已自动部署并重启服务）"
      rc=$?
    else
      err "尚未安装 acme.sh"; rc=1
    fi
  else
    warn "无效选择"; rc=1
  fi
  [[ ${1:-} != pause ]] || pause
  return "$rc"
}

update_core() {
  local cur new
  cur=$(core_version); new=$(latest_version)
  echo "当前内核: ${cur:-未安装}    最新版本: ${new:-未知}"
  confirm "安装/更新到 ${new:-最新版}?" y || return 0
  activate_core "$new"
}

# Both automatic updates and explicit versions use this rollback boundary.
activate_core() {
  local version=${1:-} backup="" log had_core=0 was_active=0 restart_attempted=0 restored=1
  local LAST_SNAP="" SNAPSHOT_RESTORED=0
  snapshot || return 1
  if [[ -f $SB_BIN ]]; then
    had_core=1
    backup=$(mktemp "${SB_BIN}.backup.XXXXXX") || return 1
    if ! cp -p "$SB_BIN" "$backup"; then
      rm -f "$backup"; err "内核备份失败，已取消更新"; return 1
    fi
  fi
  svc is-active && was_active=1
  log=$(mktemp) || { [[ -z $backup ]] || rm -f "$backup"; return 1; }
  if ! install_core "$version"; then
    rm -f "$log"; [[ -z $backup ]] || rm -f "$backup"
    return 1
  fi
  sb_args
  if refresh_builtin_acme_configs && "$SB_BIN" "${SB_ARGS[@]}" check >"$log" 2>&1 && write_service; then
    restart_attempted=1
    if restart_service_checked; then
      rm -f "$log"; [[ -z $backup ]] || rm -f "$backup"
      info "内核已更新并重启"
      return 0
    fi
  else
    err "新内核配置校验或服务配置失败"; cat "$log" >&2
  fi
  rm -f "$log"
  if ((had_core)); then
    mv -f "$backup" "$SB_BIN" || { restored=0; err "旧内核恢复失败，备份保留在 $backup"; }
  else
    rm -f "$SB_BIN" || restored=0
  fi
  restore_snapshot || restored=0
  if ((restored && had_core && was_active)); then
    if ! write_service || ! restart_service_checked; then
      restored=0; err "旧内核已恢复，但服务仍未正常运行，请检查日志"
    fi
  elif ((restart_attempted)); then
    svc stop >/dev/null 2>&1 || { restored=0; err "更新失败后无法停止服务，请检查服务状态"; }
  fi
  ((restored == 0)) || warn "更新未生效，已恢复更新前的内核和配置"
  return 1
}

core_menu() {
  local c version
  ui_title '内核管理'
  ui_item 1 '安装 / 更新最新版'; ui_item 2 '安装指定版本'; ui_item 3 '查看当前版本'; ui_item 0 '返回'
  c=$(ask_choice "请选择" 3) || return 0
  case $c in
    1) update_core ;;
    2) version=$(ask "版本号（如 1.12.0）") || return 1
       [[ -n $version ]] || { warn "版本号不能为空"; return 1; }
       activate_core "$version" ;;
    3) echo "$(core_version || echo 未安装)" ;;
  esac
}

restart_script() {
  local reply
  read -erp "按回车重新运行 sb..." reply || exit 0
  # Release the old process's lock before the new script acquires its own.
  exec 9>&-
  exec bash "$SB_CMD"
  err "重新运行失败，请手动运行 sb"
  exit 1
}

validate_script_artifact() {
  local file=$1 version trailer
  [[ -s $file ]] || { err "下载的脚本为空，已取消更新"; return 1; }
  bash -n "$file" || { err "下载的脚本语法有误，已取消"; return 1; }
  if grep -q '^SB_SOURCE_DIR=' "$file"; then
    err "下载的是源码入口，缺少配套模块。请将 SCRIPT_URL 改为 Release 的 sb.sh 下载地址"
    return 1
  fi
  version=$(sed -n 's/^SB_VERSION="\([^"]*\)"$/\1/p' "$file")
  [[ $version =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-(alpha|beta|rc)\.(0|[1-9][0-9]*))?$ ]] || {
    err "脚本缺少唯一有效版本号，已取消更新"; return 1;
  }
  trailer=$'if [[ ${BASH_SOURCE[0]} == "$0" ]]; then\n  main "$@"\n  exit $?\nfi'
  if ! grep -Fxq '# Generated by scripts/build.sh; edit sb.sh and lib/*.sh instead.' "$file" ||
     ! grep -q '^main() {' "$file" || ! grep -q '^usage() {' "$file" ||
     [[ $(tail -n 4 "$file") != "$trailer" ]]; then
    err "下载内容不是完整的独立发布脚本，已取消更新"
    return 1
  fi
}

verify_script_checksum() {
  local file=$1 sums expected actual
  # Release assets ship a sibling checksum file, including through GH proxies.
  case $SCRIPT_URL in
    */releases/latest/download/sb.sh|*/releases/download/*/sb.sh) ;;
    *) return 0 ;;
  esac
  sums=$(mktemp) || return 1
  if ! curl -fsSL "${SCRIPT_URL%/*}/SHA256SUMS" -o "$sums"; then
    rm -f "$sums"; err "无法下载发布校验和，已取消更新"; return 1
  fi
  expected=$(awk '$2 == "sb.sh" || $2 == "*sb.sh" {print $1}' "$sums")
  rm -f "$sums"
  [[ $expected =~ ^[a-fA-F0-9]{64}$ ]] || { err "发布校验和无效"; return 1; }
  actual=$(openssl dgst -sha256 "$file") || return 1
  actual=${actual##* }
  [[ $actual == "$(printf '%s' "$expected" | tr 'A-F' 'a-f')" ]] || {
    err "脚本 SHA256 校验失败，已取消更新"; return 1;
  }
}

update_script() {
  local tmp new
  [[ -n $SCRIPT_URL ]] || { err "未设置 SCRIPT_URL，无法在线更新。可用 SCRIPT_URL=<直链> sb update 指定一次"; return 1; }
  tmp=$(mktemp) || return 1
  curl -fsSL "$SCRIPT_URL" -o "$tmp" || { err "下载失败"; rm -f "$tmp"; return 1; }
  if ! validate_script_artifact "$tmp" || ! verify_script_checksum "$tmp"; then
    rm -f "$tmp"; return 1
  fi
  new=$(sed -n 's/^SB_VERSION="\(.*\)"/\1/p' "$tmp" | head -n1)
  info "当前 v${SB_VERSION}，远程 v${new:-?}"
  confirm "更新脚本?" y || { rm -f "$tmp"; return 0; }
  if ! install -m 755 "$tmp" "$SB_CMD.new" || ! mv -f "$SB_CMD.new" "$SB_CMD"; then
    rm -f "$tmp" "$SB_CMD.new"
    err "脚本安装失败，未重新运行"
    return 1
  fi
  rm -f "$tmp"
  save_conf
  if [[ ${1:-} == restart ]]; then
    info "脚本已更新"
    restart_script
  fi
  info "脚本已更新，请重新运行 sb"
}

uninstall_all() {
  local id
  confirm "确认卸载 sing-box 及 sb 命令?" n || return 0
  for id in $(list_ids); do meta_load "$id" && fw_close "$N_LPORT" "$(proto_net)"; done
  svc stop >/dev/null 2>&1; svc disable >/dev/null 2>&1
  rm -f /etc/systemd/system/$SB_SERVICE.service /etc/init.d/$SB_SERVICE "$SB_BIN" "$SB_BIN.bak"
  has_systemd && systemctl daemon-reload
  if ! confirm "保留配置与证书目录 $SB_DIR ?" y; then
    rm -rf "$SB_DIR" "$SB_WORKDIR"
    if [[ -x $ACME_SH ]] && confirm "同时卸载 acme.sh?" n; then "$ACME_SH" --uninstall >/dev/null 2>&1; rm -rf "$ACME_HOME"; fi
  fi
  rm -f "$SB_CMD"
  info "卸载完成"
}
